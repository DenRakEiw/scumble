// The Comfy Cloud jobs whose answer Scumble has not taken yet (docs/PLAN_COMFY_SDK.md S6): a run on the Comfy API v2
// notes its job here at the submit and takes it out at its end, so a crash or a quit while a job ran leaves the note
// (and so does a run whose job finished or may still run but whose picture never came: comfycloud.runV2, which then
// ends its words with KEPT). The window asks for the notes after its documents are back, again when main says the
// notes changed, and every 90 s while some are kept (comfycloud.recoverJobs through providers/index.js): a job that
// finished meanwhile comes back as a picture the window opens as a document of its own, and its note goes only when the
// window says it has it (ack). Nothing is ever sent again; only a job's own result is read. A job whose run is still
// in flight in this process (`flying`) is left to its run.
//
// <userData>/cloudjobs.json: { version: 1, jobs: [{ jobId, model, recipe, node, saveId, started }] } (a locally kept
// picture adds provider, file and mime; a kept split also kind "layers", its file a `.split`), written whole (a
// temp file, then a rename). A Comfy Cloud note older than MAX_AGE_MS is dropped unread (Comfy keeps a job's outputs
// for a limited time; locally kept files under results/ stay until opened and acked). Every change is one synchronous
// read-modify-write, so the notes of runs that end at the same time never overwrite each other (one main process holds
// the data folder); a change whose read fails for any reason but a missing or broken file writes nothing, so it cannot
// replace the notes it could not read.
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const MAX_AGE_MS = 24 * 60 * 60 * 1000;
const MAX_ENTRIES = 50;
const FILE = "cloudjobs.json";
// the end of a run's words when its job's note stays (docs/PLAN_COMFY_SDK.md, the fix contract's section 3)
const KEPT = "Scumble keeps the job and opens its picture as a document of its own when Comfy has it.";

/** The ids of the jobs whose run is in flight in this process right now (comfycloud.runV2 adds and takes them out). */
const flying = new Set();

/**
 * The ids whose note this process took out (a run's end, an ack, a read that settled it), so an ask leaves such a note
 * alone and takes it out again: a note whose removal Windows refused never opens its picture a second time. A note put
 * back (add, keep) leaves the set.
 */
const settled = new Set();
const SETTLED_MAX = 1000;
function settle(id) {
    settled.delete(id);
    settled.add(id);
    if (settled.size > SETTLED_MAX) settled.delete(settled.values().next().value);
}

/** An unlink, a rename or a read, tried again a few times when Windows holds the file a moment (a scanner, an indexer). */
function retrying(op) {
    for (let i = 0; ; i++) {
        try { return op(); } catch (err) {
            if (i >= 4 || !/^(EPERM|EBUSY|EACCES)$/.test(String(err && err.code))) throw err;
            Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 25 * (i + 1));
        }
    }
}

/** A plain file name inside `<userData>/results/` (generated by main, never a path or `..`). */
function cleanFile(f) {
    return typeof f === "string" && /^[A-Za-z0-9._-]{1,120}$/.test(f) && f !== "." && f !== ".." ? f : null;
}

/** Removes a kept picture file under `<dir>/results/`, best effort. */
function unlinkResult(dir, f) {
    const name = cleanFile(f);
    if (!dir || !name) return;
    try { retrying(() => fs.unlinkSync(path.join(dir, "results", name))); } catch (_) { /* gone or held */ }
}

/**
 * Removes stray files (`*.tmp` or pictures no note names) under `<dir>/results/`. Returns the names removed, or `null`
 * when `cloudjobs.json` is held past retries (so the caller tries again on a later ask without deleting valid files).
 */
function sweepResults(dir) {
    if (!dir) return [];
    const resDir = path.join(dir, "results");
    let names;
    try { names = fs.readdirSync(resDir); } catch (err) {
        return err && err.code === "ENOENT" ? [] : null;
    }
    if (!names.length) return [];
    let jobs;
    try { jobs = read(dir, true); } catch (_) { return null; }
    const referenced = new Set();
    for (const e of jobs) {
        const clean = cleanFile(e && e.file);
        if (clean) referenced.add(clean);
    }
    const removed = [];
    for (const name of names) {
        if (!name.endsWith(".tmp") && referenced.has(name)) continue;
        try {
            retrying(() => fs.unlinkSync(path.join(resDir, name)));
            removed.push(name);
        } catch (_) { /* held or already gone */ }
    }
    return removed;
}

/**
 * The notes. No file, or one that is not JSON, is no notes; any other failure to read (a file Windows still holds after
 * the retries) throws when `strict` (a change must not write over notes it could not read), else reads as no notes.
 */
function read(dir, strict = false) {
    let text;
    try { text = retrying(() => fs.readFileSync(path.join(dir, FILE), "utf8")); } catch (err) {
        if (strict && !(err && err.code === "ENOENT")) throw err;
        return [];
    }
    let j;
    try { j = JSON.parse(text); } catch (_) { return []; }
    return Array.isArray(j && j.jobs) ? j.jobs.filter((e) => e && typeof e.jobId === "string" && e.jobId) : [];
}

function write(dir, jobs) {
    const file = path.join(dir, FILE);
    if (!jobs.length) {
        if (fs.existsSync(file)) retrying(() => fs.unlinkSync(file));
        return;
    }
    const tmp = file + ".tmp";
    fs.writeFileSync(tmp, JSON.stringify({ version: 1, jobs }, null, 1));
    retrying(() => fs.renameSync(tmp, file));
}

/**
 * The notes under `dir` (the app's userData). No method throws: a note that cannot be written only means a crashed
 * run's result is not brought back. `pushedOut(entries)` hears the notes a full file pushed out (the oldest past
 * MAX_ENTRIES, after the ones past MAX_AGE_MS that a read would drop anyway), so they can be named in the log.
 */
function store(dir, { pushedOut = null } = {}) {
    const change = (fn) => { try { const jobs = read(dir, true); const next = fn(jobs); if (next) { write(dir, next); return true; } } catch (_) { /* see above */ } return false; };
    return {
        dir,
        add(entry) {
            settled.delete(String(entry.jobId));
            let aged = [], out = [];
            const wrote = change((jobs) => {
                const rest = jobs.filter((e) => e.jobId !== String(entry.jobId));
                const item = {
                    jobId: String(entry.jobId),
                    model: entry.model || null,
                    recipe: entry.recipe || null,
                    node: entry.node || null,
                    saveId: entry.saveId != null ? String(entry.saveId) : null,
                    started: +entry.started || Date.now(),
                };
                if (entry.provider) item.provider = String(entry.provider);
                const clean = cleanFile(entry.file);
                if (clean) {
                    item.file = clean;
                    item.mime = typeof entry.mime === "string" && entry.mime ? entry.mime : "image/png";
                    // a split's whole answer in one file (writeSplit): the window lands its layers, not one picture
                    if (entry.kind === "layers") item.kind = "layers";
                }
                rest.push(item);
                if (rest.length <= MAX_ENTRIES) return rest;
                const now = Date.now();
                aged = rest.filter((e) => !e.file && now - (+e.started || 0) >= MAX_AGE_MS);
                const young = rest.filter((e) => e.file || now - (+e.started || 0) < MAX_AGE_MS);
                out = young.length > MAX_ENTRIES ? young.slice(0, young.length - MAX_ENTRIES) : [];
                return young.slice(-MAX_ENTRIES);
            });
            if (wrote) {
                for (const e of out) if (e.file) unlinkResult(dir, e.file);
                if (out.length && typeof pushedOut === "function") { try { pushedOut(out); } catch (_) { /* a log line only */ } }
            }
            return wrote;
        },
        remove(jobId) { this.drop([jobId]); },
        /** Takes out the notes of these jobs alone; a note added meanwhile (a run that started) stays. */
        drop(ids) {
            const gone = new Set((ids || []).map(String));
            if (!gone.size) return;
            for (const id of gone) settle(id);
            change((jobs) => { const left = jobs.filter((e) => !gone.has(e.jobId)); return left.length === jobs.length ? null : left; });
        },
        list() { return read(dir); },
        /** Writes exactly these notes (the tests' seed). */
        keep(jobs) { for (const e of jobs || []) settled.delete(String(e && e.jobId)); try { write(dir, jobs); } catch (_) { /* see above */ } },
    };
}

// ---- a split's whole answer kept in one file (docs/BUGS.md: a split lost when its window went away) --------------
// `<id>.split` under results/: the magic, the head's length (uint32 LE), the head as JSON, then each layer's picture
// one after another. The head holds what the window lands a split from (each layer's name, box, stacking order, mime,
// description; the run's info, notes, missing) and where each picture lies (`offset` from the end of the head,
// `length`), so the window takes the pictures one at a time from the file and main never holds a recovered split
// whole. One file per split: the notes, the sweep and an ack treat it as any kept picture.

const SPLIT_MAGIC = Buffer.from("SCSPLIT1", "ascii");
const SPLIT_HEAD_MAX = 4 * 1024 * 1024;   // a head of 101 layers' names and descriptions is a few hundred KB at most
const SPLIT_LAYERS_MAX = 512;
const SPLIT_TEXT = { name: 400, description: 4000, mime: 100 };

/**
 * Writes a split's answer to the open file `fd`: `out` the adapter's answer ({ layers: [{ bytes, mime, z_index, base,
 * bounding_box, full, name, description, size }], info, missing }), `extra` more of the head (seconds, prompt, notes).
 * -> the number of layers written.
 */
function writeSplit(fd, out, extra = {}) {
    const list = Array.isArray(out && out.layers) ? out.layers : [];
    if (!list.length) throw new Error("the split's answer holds no pictures");
    if (list.length > SPLIT_LAYERS_MAX) throw new Error(`the split's answer holds ${list.length} pictures, more than ${SPLIT_LAYERS_MAX}`);
    const bufs = list.map((l) => { const b = l && l.bytes; return Buffer.isBuffer(b) ? b : b instanceof Uint8Array ? Buffer.from(b.buffer, b.byteOffset, b.byteLength) : Buffer.from(b || []); });
    let offset = 0;
    const layers = list.map((l, i) => {
        const row = {
            mime: String(l.mime || "image/png").slice(0, SPLIT_TEXT.mime),
            z_index: Number.isFinite(+l.z_index) ? +l.z_index : i,
            base: !!l.base,
            bounding_box: l.bounding_box && typeof l.bounding_box === "object" ? l.bounding_box : null,
            full: !!l.full,
            name: String(l.name == null ? "" : l.name).slice(0, SPLIT_TEXT.name),
            description: String(l.description == null ? "" : l.description).slice(0, SPLIT_TEXT.description),
            size: l.size == null ? null : l.size,
            offset, length: bufs[i].length,
        };
        offset += bufs[i].length;
        return row;
    });
    const head = Buffer.from(JSON.stringify({ version: 1, ...extra, info: out.info == null ? null : out.info, missing: Array.isArray(out.missing) ? out.missing.map(String) : [], layers }), "utf8");
    if (head.length > SPLIT_HEAD_MAX) throw new Error("the split's head is too large to keep");
    const len = Buffer.alloc(4);
    len.writeUInt32LE(head.length, 0);
    for (const b of [SPLIT_MAGIC, len, head, ...bufs]) fs.writeSync(fd, b, 0, b.length);
    return layers.length;
}

/**
 * A kept split's head, read alone (its pictures stay on disk): -> { head, start (where the pictures begin), size }.
 * Throws with `code` "EBADSPLIT" for a file that is not a whole split (a wrong magic, a head past its limit, a picture
 * past the file's end); any other read error is the file system's (ENOENT, a held file).
 */
function readSplitHead(file) {
    const bad = (why) => Object.assign(new Error(`not a kept split: ${why}`), { code: "EBADSPLIT" });
    const fd = retrying(() => fs.openSync(file, "r"));
    try {
        const size = fs.fstatSync(fd).size;
        const pre = Buffer.alloc(SPLIT_MAGIC.length + 4);
        if (size < pre.length || fs.readSync(fd, pre, 0, pre.length, 0) !== pre.length) throw bad("too short");
        if (!pre.subarray(0, SPLIT_MAGIC.length).equals(SPLIT_MAGIC)) throw bad("wrong magic");
        const n = pre.readUInt32LE(SPLIT_MAGIC.length);
        if (!(n > 0 && n <= SPLIT_HEAD_MAX) || pre.length + n > size) throw bad("bad head length");
        const hb = Buffer.alloc(n);
        if (fs.readSync(fd, hb, 0, n, pre.length) !== n) throw bad("head cut short");
        let head;
        try { head = JSON.parse(hb.toString("utf8")); } catch (_) { throw bad("head not JSON"); }
        const start = pre.length + n;
        const layers = head && Array.isArray(head.layers) ? head.layers : null;
        if (!layers || !layers.length || layers.length > SPLIT_LAYERS_MAX) throw bad("no layers");
        for (const l of layers) {
            if (!l || !Number.isInteger(l.offset) || !Number.isInteger(l.length) || l.offset < 0 || l.length <= 0 || start + l.offset + l.length > size) throw bad("a picture past the end");
        }
        return { head, start, size };
    } finally { fs.closeSync(fd); }
}

/** One picture of a kept split, read from its place in the file. */
function readSplitPart(file, at, length) {
    const fd = retrying(() => fs.openSync(file, "r"));
    try {
        const b = Buffer.alloc(length);
        let got = 0;
        while (got < length) {
            const r = fs.readSync(fd, b, got, length - got, at + got);
            if (r <= 0) throw new Error("the kept split's file is cut short");
            got += r;
        }
        return b;
    } finally { fs.closeSync(fd); }
}

module.exports = { store, flying, settled, retrying, cleanFile, unlinkResult, sweepResults, writeSplit, readSplitHead, readSplitPart, MAX_AGE_MS, FILE, KEPT };
